# Prepares the x86_64-pc-windows-gnu Rust toolchain to build Prism.
#
# rustup's GNU toolchain ships dlltool.exe without the GNU assembler it needs, so crates that use
# raw-dylib imports (windows-sys >= 0.60, used by the GUI and CLI stacks) fail to build. This script
# builds a stand-in that writes GNU-style import libraries itself (tools/dlltool-shim/main.rs),
# installs it as %CARGO_HOME%\bin\prism-dlltool.exe and points the GNU target at it in the
# user-level %CARGO_HOME%\config.toml, Cargo's place for machine-specific settings. rustc resolves
# -C dlltool relative to each crate's directory, so the path must be absolute and cannot live in
# the project's committed .cargo/config.toml. Re-running the script replaces its section; an
# existing user config is backed up first. The MSVC toolchain does not need this step.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$cargoHome = if ($env:CARGO_HOME) { $env:CARGO_HOME } else { Join-Path $HOME '.cargo' }
$bin = Join-Path $PSScriptRoot 'bin'
New-Item -ItemType Directory -Force $bin, (Join-Path $cargoHome 'bin') | Out-Null
$built = Join-Path $bin 'dlltool.exe'
rustc -O --edition 2021 -o $built (Join-Path $PSScriptRoot 'dlltool-shim\main.rs')
if ($LASTEXITCODE -ne 0) { throw 'failed to build dlltool shim' }
$shim = Join-Path $cargoHome 'bin\prism-dlltool.exe'
Copy-Item $built $shim -Force

$begin = '# >>> generated by tools/setup-gnu-toolchain.ps1 (Prism: dlltool for the GNU toolchain)'
$end = '# <<< generated by tools/setup-gnu-toolchain.ps1'
$pattern = [regex]::Escape('# >>> generated by tools/setup-gnu-toolchain.ps1') + '[^\r\n]*\r?\n[\s\S]*?' + [regex]::Escape($end) + '\r?\n?'
$section = @"
$begin
[target.x86_64-pc-windows-gnu]
rustflags = ["-C", "dlltool=$($shim.Replace('\', '/'))"]
$end
"@

function Write-Utf8NoBom($path, $text) {
  # TOML parsers reject a byte-order mark; WriteAllText writes UTF-8 without one.
  [System.IO.File]::WriteAllText($path, $text)
}

# User-level config: replace our section, keep everything else, back up the previous file.
$userConfig = Join-Path $cargoHome 'config.toml'
$existing = if (Test-Path $userConfig) { [System.IO.File]::ReadAllText($userConfig) } else { '' }
$kept = [regex]::Replace($existing, $pattern, '').TrimEnd()
$updated = (($kept + "`n`n" + $section).TrimStart()) + "`n"
if ($updated -ne $existing) {
  if ($existing) {
    $backup = "$userConfig.bak-$(Get-Date -Format yyyyMMdd-HHmmss)"
    Copy-Item $userConfig $backup
    Write-Host "backed up $userConfig to $backup"
  }
  Write-Utf8NoBom $userConfig $updated
}

# Earlier versions wrote the section into the project's config; remove it from there.
$projectConfig = Join-Path $root '.cargo\config.toml'
if (Test-Path $projectConfig) {
  $text = [System.IO.File]::ReadAllText($projectConfig)
  $clean = [regex]::Replace($text, $pattern, '').TrimEnd() + "`n"
  if ($clean -ne $text) { Write-Utf8NoBom $projectConfig $clean }
}
Write-Host "dlltool shim ready: $shim (configured in $userConfig)"
Write-Host "Now run: cargo build --release   (from $root)"
